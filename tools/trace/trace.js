#!/usr/bin/env node
// Requirements Traceability Gate.
//
// Reconciles three sources of truth that otherwise drift freely:
//   1. Spec requirements   — `- **R.N** — summary` bullets in docs/specs/*.md
//   2. Feature coverage     — `@R.N` tags on scenarios in tests/acceptance/features/**
//   3. Actual results       — Playwright's JSON report (which scenarios passed)
//
// `generate` writes tests/acceptance/test-plan.yaml + TRACEABILITY.md from
// sources 1+2 (deterministic, results-independent). `check` regenerates in
// memory and fails (exit 1) on any of: an uncovered requirement, an orphan
// `@R.N` tag, a "covered" scenario that did not pass (with --results), or a
// stale committed artifact.
//
// Zero dependencies — Node built-ins only. The pure functions are exported for
// unit testing; the CLI runs only when executed directly.

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const PLAN_PATH = "tests/acceptance/test-plan.yaml";
const MATRIX_PATH = "TRACEABILITY.md";
const SPECS_DIR = "docs/specs";
const FEATURES_DIR = "tests/acceptance/features";
const GENERATED_NOTE =
  "Generated by tools/trace/trace.js — run `pnpm trace:gen`. Do not edit by hand.";

// ---------------------------------------------------------------------------
// Parsing (pure)
// ---------------------------------------------------------------------------

// Accept any dash (hyphen-minus, en-dash, em-dash) so a typo doesn't silently
// drop a requirement. `(.*)` allows an empty summary to still be captured (and
// flagged MALFORMED) rather than skipped.
const REQ_BULLET = /^\s*-\s+\*\*(R\.\d+)\*\*\s+[-–—]\s+(.*)$/;

// Normalise a requirement summary so the generated artifact is byte-stable:
// collapse internal whitespace, strip a single trailing period.
function normaliseSummary(text) {
  return text.replace(/\s+/g, " ").trim().replace(/\.$/, "");
}

// Parse `- **R.N** — summary` bullets, joining indented continuation lines.
export function parseRequirements(markdown) {
  const lines = markdown.split(/\r?\n/);
  const requirements = [];
  let current = null;
  const flush = () => {
    if (current) {
      requirements.push({
        id: current.id,
        summary: normaliseSummary(current.parts.join(" ")),
      });
      current = null;
    }
  };
  for (const line of lines) {
    const m = line.match(REQ_BULLET);
    if (m) {
      flush();
      current = { id: m[1], parts: [m[2]] };
      continue;
    }
    if (
      current &&
      /^\s{2,}\S/.test(line) &&
      !/^\s*-\s/.test(line) &&
      !/^\s*#/.test(line)
    ) {
      current.parts.push(line.trim());
      continue;
    }
    flush();
  }
  flush();
  return requirements;
}

const FEATURE_RE = /^\s*Feature:\s*(.+)$/;
const SCENARIO_RE = /^\s*Scenario(?: Outline)?:\s*(.+)$/;
const TAG_TOKEN = /@[\w.]+/g;
const REQ_TAG = /^@(R\.\d+)$/;

// Parse a .feature into a flat list of scenario records:
// { feature, scenario, reqTags: ["R.1", ...] }.
export function parseFeature(featureText, featureName) {
  const lines = featureText.split(/\r?\n/);
  const scenarios = [];
  let featureTags = [];
  let tagBuffer = [];
  for (const line of lines) {
    if (/^\s*@/.test(line)) {
      tagBuffer.push(...(line.match(TAG_TOKEN) ?? []));
      continue;
    }
    if (FEATURE_RE.test(line)) {
      featureTags = tagBuffer;
      tagBuffer = [];
      continue;
    }
    const sc = line.match(SCENARIO_RE);
    if (sc) {
      const tags = [...featureTags, ...tagBuffer];
      const reqTags = tags
        .map((t) => (t.match(REQ_TAG) ?? [])[1])
        .filter(Boolean);
      scenarios.push({ feature: featureName, scenario: sc[1].trim(), reqTags });
      tagBuffer = [];
    }
  }
  return scenarios;
}

// Walk Playwright's JSON report into [{ scenario, feature, tags, passed }].
// Tags arrive with the leading `@` stripped (e.g. "R.1"); a scenario passed
// when every attempt's outcome is "expected" or "flaky". Scenario Outline rows
// are titled "Example #N", so they inherit their parent suite's (scenario) name.
function deriveFeature(file) {
  if (!file) return null;
  return path.basename(file).replace(/\.spec\.(js|ts|mjs|cjs)$/, "");
}

export function parseResults(report) {
  const out = [];
  const walk = (suite, file) => {
    const f = suite.file ?? file;
    for (const spec of suite.specs ?? []) {
      const tests = spec.tests ?? [];
      const passed =
        tests.length > 0 &&
        tests.every((t) => t.status === "expected" || t.status === "flaky");
      const scenario = /^Example #\d+$/.test(spec.title)
        ? (suite.title ?? spec.title)
        : spec.title;
      out.push({
        scenario,
        feature: deriveFeature(spec.file ?? f),
        tags: spec.tags ?? [],
        passed,
      });
    }
    for (const child of suite.suites ?? []) walk(child, f);
  };
  for (const suite of report.suites ?? []) walk(suite, undefined);
  return out;
}

// ---------------------------------------------------------------------------
// Matrix + rendering (pure)
// ---------------------------------------------------------------------------

// specs: [{ id, source, requirements: [{id, summary}] }]
// scenarios: flat [{ feature, scenario, reqTags }]
export function buildMatrix(specs, scenarios) {
  return {
    specs: specs.map((spec) => ({
      id: spec.id,
      source: spec.source,
      requirements: spec.requirements.map((req) => ({
        id: req.id,
        summary: req.summary,
        scenarios: scenarios
          .filter((sc) => sc.reqTags.includes(req.id))
          .map((sc) => ({
            feature: sc.feature,
            scenario: sc.scenario,
            status: "covered",
          })),
      })),
    })),
  };
}

function yamlScalar(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

export function renderYaml(matrix) {
  const lines = [`# ${GENERATED_NOTE}`, "specs:"];
  for (const spec of matrix.specs) {
    lines.push(`  - id: ${spec.id}`);
    lines.push(`    source: ${spec.source}`);
    lines.push("    requirements:");
    for (const req of spec.requirements) {
      lines.push(`      - id: ${req.id}`);
      lines.push(`        summary: ${yamlScalar(req.summary)}`);
      if (req.scenarios.length === 0) {
        lines.push("        scenarios: []");
      } else {
        lines.push("        scenarios:");
        for (const sc of req.scenarios) {
          lines.push(`          - feature: ${sc.feature}`);
          lines.push(`            scenario: ${yamlScalar(sc.scenario)}`);
          lines.push(`            status: ${sc.status}`);
        }
      }
    }
  }
  return lines.join("\n") + "\n";
}

export function renderMarkdown(matrix) {
  let total = 0;
  let covered = 0;
  for (const spec of matrix.specs) {
    for (const req of spec.requirements) {
      total += 1;
      if (req.scenarios.length > 0) covered += 1;
    }
  }
  const lines = [
    "# Requirements Traceability",
    "",
    `<!-- ${GENERATED_NOTE} -->`,
    "",
    `**${covered} of ${total}** requirements covered by acceptance scenarios.`,
    "",
  ];
  for (const spec of matrix.specs) {
    lines.push(`## ${spec.id}`);
    lines.push("");
    lines.push(`Source: \`${spec.source}\``);
    lines.push("");
    lines.push("| Requirement | Summary | Covered by |");
    lines.push("| --- | --- | --- |");
    for (const req of spec.requirements) {
      const covers =
        req.scenarios.length === 0
          ? "— none —"
          : req.scenarios
              .map((sc) => `\`${sc.feature}\` › ${sc.scenario}`)
              .join("<br>");
      lines.push(`| ${req.id} | ${req.summary} | ${covers} |`);
    }
    lines.push("");
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}

// ---------------------------------------------------------------------------
// Rules (pure)
// ---------------------------------------------------------------------------

// Returns a list of violation strings. `results` (optional) enables the
// covered⇒passed rule.
//
// A result row proves a covered scenario passed. Joins by scenario title + tag,
// disambiguated by feature filename when both sides know it (so duplicate titles
// across feature files don't cross-match); falls back to title + tag when the
// feature is unknown.
function resultPasses(results, reqId, sc) {
  return !!results.find(
    (r) =>
      r.passed &&
      r.scenario === sc.scenario &&
      r.tags.includes(reqId) &&
      (r.feature == null || r.feature === sc.feature),
  );
}

export function findViolations(matrix, scenarios, results) {
  const violations = [];
  const known = new Set();
  for (const spec of matrix.specs)
    for (const req of spec.requirements) known.add(req.id);

  for (const spec of matrix.specs) {
    for (const req of spec.requirements) {
      if (!req.summary || !req.summary.trim()) {
        violations.push(
          `MALFORMED ${req.id} (${spec.id}): empty requirement summary`,
        );
      }
      if (req.scenarios.length === 0) {
        violations.push(
          `UNCOVERED ${req.id} (${spec.id}): no scenario tagged @${req.id}`,
        );
      }
    }
  }

  const seenOrphans = new Set();
  for (const sc of scenarios) {
    for (const tag of sc.reqTags) {
      if (!known.has(tag)) {
        const key = `${tag}|${sc.feature}|${sc.scenario}`;
        if (!seenOrphans.has(key)) {
          seenOrphans.add(key);
          violations.push(
            `ORPHAN @${tag} (${sc.feature} › ${sc.scenario}): no matching requirement in any spec`,
          );
        }
      }
    }
  }

  if (results) {
    for (const spec of matrix.specs) {
      for (const req of spec.requirements) {
        for (const sc of req.scenarios) {
          if (!resultPasses(results, req.id, sc)) {
            violations.push(
              `UNPROVEN ${req.id}: scenario "${sc.scenario}" (${sc.feature}) has no passing acceptance result`,
            );
          }
        }
      }
    }
  }

  return violations;
}

// Annotate each scenario with whether it passed in the given results (null when
// no results were supplied). Pure — used by the `matrix` command and consumed by
// the Workbench cockpit's verification panel.
export function augmentMatrix(matrix, results) {
  return {
    specs: matrix.specs.map((spec) => ({
      ...spec,
      requirements: spec.requirements.map((req) => ({
        ...req,
        scenarios: req.scenarios.map((sc) => ({
          ...sc,
          passed: results ? resultPasses(results, req.id, sc) : null,
        })),
      })),
    })),
  };
}

// ---------------------------------------------------------------------------
// CLI (impure)
// ---------------------------------------------------------------------------

function listFiles(dir, ext) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full, ext));
    else if (entry.name.endsWith(ext)) out.push(full);
  }
  return out.sort();
}

function loadSpecs(root) {
  const dir = path.join(root, SPECS_DIR);
  return listFiles(dir, ".md").map((file) => ({
    id: path.basename(file, ".md"),
    source: path.relative(root, file).split(path.sep).join("/"),
    requirements: parseRequirements(readFileSync(file, "utf8")),
  }));
}

function loadScenarios(root) {
  const dir = path.join(root, FEATURES_DIR);
  return listFiles(dir, ".feature").flatMap((file) =>
    parseFeature(readFileSync(file, "utf8"), path.basename(file)),
  );
}

function optValue(args, name) {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
}

function readIfExists(file) {
  return existsSync(file) ? readFileSync(file, "utf8") : null;
}

// Normalise line endings + trailing whitespace so staleness checks don't trip on
// CRLF (e.g. a Windows checkout) or editor-added trailing spaces.
function normalizeArtifact(s) {
  return s == null
    ? null
    : s
        .replace(/\r\n/g, "\n")
        .replace(/[ \t]+$/gm, "")
        .replace(/\n+$/, "\n");
}

// Warn (don't fail) on tags that look like requirement ids but are malformed
// (e.g. @R.1a) — they're otherwise silently ignored.
function warnMalformedTags(root) {
  for (const file of listFiles(path.join(root, FEATURES_DIR), ".feature")) {
    const tokens = readFileSync(file, "utf8").match(/@R\.[\w.-]+/g) ?? [];
    for (const t of tokens) {
      if (!/^@R\.\d+$/.test(t)) {
        console.warn(
          `trace: warning — malformed requirement tag "${t}" in ${path.basename(file)} (expected @R.<number>)`,
        );
      }
    }
  }
}

// Defensive shape check so a regression in augmentMatrix fails loudly in the tool
// rather than producing bad JSON the cockpit then mis-renders.
function validateMatrixShape(m) {
  if (!m || !Array.isArray(m.specs)) {
    throw new Error("matrix: specs must be an array");
  }
  for (const spec of m.specs) {
    if (typeof spec.id !== "string" || !Array.isArray(spec.requirements)) {
      throw new Error(`matrix: malformed spec ${spec?.id}`);
    }
    for (const req of spec.requirements) {
      if (typeof req.id !== "string" || !Array.isArray(req.scenarios)) {
        throw new Error(`matrix: malformed requirement ${req?.id}`);
      }
    }
  }
  return m;
}

function main(argv) {
  const [cmd, ...rest] = argv;
  const root = path.resolve(optValue(rest, "--root") ?? process.cwd());
  const specs = loadSpecs(root);
  const scenarios = loadScenarios(root);
  warnMalformedTags(root);
  const matrix = buildMatrix(specs, scenarios);
  const yaml = renderYaml(matrix);
  const markdown = renderMarkdown(matrix);
  const planFile = path.join(root, PLAN_PATH);
  const matrixFile = path.join(root, MATRIX_PATH);

  if (cmd === "generate") {
    writeFileSync(planFile, yaml);
    writeFileSync(matrixFile, markdown);
    const reqs = specs.reduce((n, s) => n + s.requirements.length, 0);
    console.log(
      `trace: wrote ${PLAN_PATH} and ${MATRIX_PATH} (${reqs} requirements across ${specs.length} spec(s)).`,
    );
    return 0;
  }

  if (cmd === "matrix") {
    const resultsPath = optValue(rest, "--results");
    let results = null;
    if (resultsPath) {
      const file = path.resolve(root, resultsPath);
      if (existsSync(file)) {
        results = parseResults(JSON.parse(readFileSync(file, "utf8")));
      }
    }
    const violations = findViolations(matrix, scenarios, results);
    const augmented = validateMatrixShape(augmentMatrix(matrix, results));
    console.log(
      JSON.stringify(
        {
          ...augmented,
          violations,
          ok: violations.length === 0,
          hasResults: results !== null,
        },
        null,
        2,
      ),
    );
    return 0;
  }

  if (cmd === "check") {
    const resultsPath = optValue(rest, "--results");
    let results = null;
    if (resultsPath && !rest.includes("--structural")) {
      const file = path.resolve(root, resultsPath);
      if (existsSync(file)) {
        results = parseResults(JSON.parse(readFileSync(file, "utf8")));
      } else {
        console.error(`trace: results file not found: ${resultsPath}`);
        return 1;
      }
    }
    const violations = findViolations(matrix, scenarios, results);
    if (normalizeArtifact(readIfExists(planFile)) !== normalizeArtifact(yaml)) {
      violations.push(
        `STALE ${PLAN_PATH}: out of date — run \`pnpm trace:gen\``,
      );
    }
    if (
      normalizeArtifact(readIfExists(matrixFile)) !==
      normalizeArtifact(markdown)
    ) {
      violations.push(
        `STALE ${MATRIX_PATH}: out of date — run \`pnpm trace:gen\``,
      );
    }
    if (violations.length > 0) {
      console.error(`trace: ${violations.length} traceability violation(s):`);
      for (const v of violations) console.error(`  ✗ ${v}`);
      return 1;
    }
    const reqs = specs.reduce((n, s) => n + s.requirements.length, 0);
    console.log(
      `trace: OK — ${reqs} requirement(s) covered${results ? " and passing" : ""}.`,
    );
    return 0;
  }

  console.error(
    "Usage: trace <generate|check|matrix> [--root <dir>] [--results <playwright.json>] [--structural]",
  );
  return 2;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exit(main(process.argv.slice(2)));
}
